#!/usr/bin/env python3
"""Golden-fixture analysis tests (tests/replay — synthetic fixtures).

The fixtures are generated by an independent Python implementation of the
dslogic-cross-v1 wire format, so passing these tests cross-validates the C
unpacker, timing analyzer and decoders against a second implementation.
"""
import json
import math
import os
import subprocess
import sys
import tempfile
import shutil

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "fixtures"))
import gen_fixtures  # noqa: E402

DSLAB = sys.argv[1] if len(sys.argv) > 1 else "./build/dslab.exe"
failures = []


def check(cond, msg):
    if not cond:
        failures.append(msg)


def run(*args, timeout=120):
    p = subprocess.run([DSLAB, *args], capture_output=True, text=True, timeout=timeout)
    lines = [l for l in p.stdout.splitlines() if l.strip()]
    j = {}
    if lines:
        try:
            j = json.loads(lines[0])
        except json.JSONDecodeError:
            failures.append(f"{args}: stdout not JSON: {lines[0][:200]!r}")
    return p, j


def approx(a, b, tol):
    return abs(a - b) <= tol


def main():
    tmp = tempfile.mkdtemp(prefix="dslab-golden-")
    try:
        made = gen_fixtures.generate(tmp)
        base = lambda name: os.path.join(tmp, name)

        # ---- timing: square1k (2 kHz square: 500 samples/period @1 MHz) ----
        p, j = run("analyze", "timing", base("square1k"), "--channel", "D0", "--json")
        check(p.returncode == 0, f"timing exit 0, got {p.returncode}")
        # starts LOW; rising at 250+500k (100) and falling at 500+500k (100)
        check(j.get("edge_count") == 200, f"200 edges, got {j.get('edge_count')}")
        check(approx(j["frequency_hz"], 2000.0, 0.1), f"freq 2000Hz, got {j.get('frequency_hz')}")
        check(approx(j["duty_cycle"], 0.5, 0.001), f"duty 0.5, got {j.get('duty_cycle')}")
        check(j["period"]["min_samples"] == 500 and j["period"]["max_samples"] == 500,
              f"period exactly 500 samples, got {j.get('period')}")
        check(j["pulse_high"]["mean_samples"] == 250, "high width 250 samples")
        check(j["pulse_low"]["mean_samples"] == 250, "low width 250 samples")
        check(j["period"].get("jitter_us_stddev", 1) == 0, "zero jitter on exact square")
        check(j.get("first_level") == 0, "starts low")

        # window restriction: first 10000 samples -> edges at 250..9750 = 39
        p, j = run("analyze", "timing", base("square1k"), "--channel", "D0",
                   "--window", "0us:10000us", "--json")
        check(j.get("edge_count") == 39, f"windowed edges 39, got {j.get('edge_count')}")
        check(j.get("analyzed_samples") == 10000, "windowed sample count")

        # two-channel delay: D1 lags D0 by 100 samples (both rise at 250/350 + 500k)
        p, j = run("analyze", "timing", base("square1k"), "--channel", "D1",
                   "--reference", "D0", "--json")
        d = j.get("channel_delay", {})
        check(d.get("first_delay_samples") == 100, f"D1-D0 delay 100, got {d}")
        check(d.get("min_delay_samples") == 100 and d.get("max_delay_samples") == 100,
              "delay stable at 100 samples")

        # ---- timing: jitter square (period 480/520 alternating) ----
        p, j = run("analyze", "timing", base("square_jitter"), "--channel", "D0", "--json")
        check(j["period"]["min_samples"] == 480, f"jitter min 480, got {j['period']['min_samples']}")
        check(j["period"]["max_samples"] == 520, f"jitter max 520, got {j['period']['max_samples']}")
        check(j["period"]["jitter_us_stddev"] > 15, "jitter stddev > 15us (480/520 alt)")

        # ---- uart decode ----
        meta = made["uart_8n1_meta"]
        p, j = run("decode", "uart", base("uart_8n1"), "--channel", "D0",
                   "--baud", "100000", "--json")
        check(p.returncode == 0, f"uart exit 0, got {p.returncode}")
        vals = [f["value"] for f in j.get("frames", [])]
        want = [f"0x{b:02x}" for b in meta["bytes"]]
        check(vals == want, f"uart bytes {want}, got {vals}")
        check(j.get("frame_count") == len(want), "frame count")
        errs = [f for f in j.get("frames", []) if f["framing_error"]]
        check(len(errs) == 1 and errs[0]["value"] == "0x00",
              f"exactly the corrupted frame flagged, got {errs}")

        # ---- i2c decode ----
        im = made["i2c_txns_meta"]
        p, j = run("decode", "i2c", base("i2c_txns"), "--scl", "D0", "--sda", "D1", "--json")
        check(p.returncode == 0, f"i2c exit 0, got {p.returncode}")
        tx = j.get("transactions", [])
        check(j.get("transaction_count") == 3, f"3 txns, got {j.get('transaction_count')}")
        t0 = tx[0]
        check(t0["address"] == "0x50" and t0["rw"] == "write", f"txn1 addr, got {t0}")
        data = [b["value"] for b in t0["bytes"]]
        check(data == ["0xa0", "0xbe", "0xef"], f"txn1 bytes, got {data}")
        acks = [b["ack"] for b in t0["bytes"]]
        check(acks == ["ACK", "ACK", "ACK"], f"txn1 acks, got {acks}")
        t1 = tx[1]
        check(t1["address"] == "0x50" and t1["rw"] == "read", "txn2 read addr")
        check(t1["bytes"][1]["ack"] == "NACK", "txn2 data byte NACK")
        t2 = tx[2]
        check(t2["address"] == "0x37" and t2["bytes"][0]["ack"] == "NACK",
              f"txn3 addr NACK, got {t2}")
        check(all(t["stop_sample"] > 0 for t in tx), "all txns have STOP")

        # ---- spi decode ----
        sm = made["spi_mode0_meta"]
        p, j = run("decode", "spi", base("spi_mode0"), "--clk", "D0", "--mosi", "D1",
                   "--miso", "D2", "--cs", "D3", "--mode", "0", "--json")
        check(p.returncode == 0, f"spi exit 0, got {p.returncode}")
        stx = j.get("transactions", [])
        check(j.get("transaction_count") == 2, f"2 spi txns, got {j.get('transaction_count')}")
        check(stx[0]["mosi_hex"] == "a5 3a", f"spi mosi, got {stx[0]['mosi_hex']}")
        check(stx[0]["miso_hex"] == "00 ff", f"spi miso, got {stx[0]['miso_hex']}")
        check(stx[1]["mosi_hex"] == "81" and stx[1]["miso_hex"] == "7e", "spi txn2")
        check(all(not t["misaligned"] for t in stx), "no misaligned frames")

        # ---- assert: passing spec (plus one not-applicable rule) ----
        spec_pass = {"rules": [
            {"id": "clk", "type": "timing.period_range", "channel": "D0",
             "min_us": 499, "max_us": 501},
            {"id": "duty", "type": "timing.duty_range", "channel": "D0",
             "min": 0.45, "max": 0.55},
            {"id": "delay", "type": "timing.channel_delay", "from": "D0", "to": "D1",
             "max_abs_us": 150},
            # D5 was not captured -> rule cannot be evaluated -> indeterminate
            {"id": "absent", "type": "timing.freq_range", "channel": "D5",
             "min_hz": 1, "max_hz": 100},
        ]}
        specf = os.path.join(tmp, "spec_pass.json")
        json.dump(spec_pass, open(specf, "w"))
        p, j = run("assert", base("square1k"), "--spec", specf, "--json")
        check(p.returncode == 0, f"assert(pass-ish) exit 0, got {p.returncode}")
        check(j.get("verdict") == "indeterminate", f"verdict indeterminate, got {j.get('verdict')}")
        vd = {r["id"]: r["verdict"] for r in j.get("rules", [])}
        check(vd.get("clk") == "pass", f"clk rule pass, got {vd}")
        check(vd.get("delay") == "pass", "delay rule pass")
        check(vd.get("absent") == "indeterminate", "absent channel -> indeterminate")

        # ---- VCD export round-trip ----
        p, j = run("export", "vcd", base("square1k"), "--json")
        check(p.returncode == 0, f"export exit 0, got {p.returncode}")
        vcd_path = j.get("path")
        check(bool(vcd_path) and os.path.isfile(vcd_path), "vcd file written")
        # minimal VCD parse: reconstruct D0 ('!' identifier) timeline
        levels = {}
        events = []
        t = 0
        for line in open(vcd_path, encoding="utf-8"):
            line = line.strip()
            if line.startswith("#"):
                t = int(line[1:])
            elif len(line) == 2 and line[0] in "01" and line[1] in "!\"":
                if line[1] == "!":
                    events.append((t, int(line[0])))
        check(len(events) == 201, f"vcd has 201 value records (init + 200 changes), got {len(events)}")
        check(events[0] == (0, 0), "vcd starts with the initial level at t=0")
        # verify a reconstructed level against the generator's own signal
        def level_at(sample):
            # vcd time unit == ns; sample->ns is exact for 1 MHz rate
            ns = sample  # 1 sample = 1000 ns... rate 1MHz
            ns = sample * 1000
            lv = 0
            for (tt, vv) in events:
                if tt > ns:
                    break
                lv = vv
            return lv
        for probe in (0, 249, 251, 7000, 49999):
            expect = gen_fixtures.square(50048, 500, 0.5, 250)[probe]
            check(level_at(probe) == expect,
                  f"vcd D0 level at sample {probe}: {level_at(probe)} != {expect}")

        # ---- assert: failing spec -> exit 5 ----
        spec_fail = {"rules": [
            {"id": "too-fast", "type": "timing.freq_range", "channel": "D0",
             "min_hz": 3000, "max_hz": 4000},
        ]}
        specf2 = os.path.join(tmp, "spec_fail.json")
        json.dump(spec_fail, open(specf2, "w"))
        p, j = run("assert", base("square1k"), "--spec", specf2, "--json")
        check(p.returncode == 5, f"assert fail exit 5, got {p.returncode}")
        check(j.get("verdict") == "fail", "verdict fail")
        check(j.get("failed") == 1, "one failed rule")

        # ---- assert on the i2c fixture ----
        spec_i2c = {"rules": [
            {"id": "addr50", "type": "i2c.address_ack", "address": "0x50",
             "scl": "D0", "sda": "D1"},
            {"id": "nonack", "type": "i2c.no_nack", "scl": "D0", "sda": "D1"},
        ]}
        specf3 = os.path.join(tmp, "spec_i2c.json")
        json.dump(spec_i2c, open(specf3, "w"))
        p, j = run("assert", base("i2c_txns"), "--spec", specf3, "--json")
        vd = {r["id"]: r["verdict"] for r in j.get("rules", [])}
        check(vd.get("addr50") == "pass", f"addr50 pass, got {vd}")
        check(vd.get("nonack") == "fail", "no_nack fails (fixture has NACKs)")
        check(p.returncode == 5, f"exit 5, got {p.returncode}")

        # ---- assert on the uart fixture ----
        spec_uart = {"rules": [
            {"id": "bytes", "type": "uart.frames", "channel": "D0", "baud": 100000,
             "contains": "48 69 21 00 ff"},
            {"id": "noerr", "type": "uart.no_errors", "channel": "D0", "baud": 100000},
        ]}
        specf4 = os.path.join(tmp, "spec_uart.json")
        json.dump(spec_uart, open(specf4, "w"))
        p, j = run("assert", base("uart_8n1"), "--spec", specf4, "--json")
        vd = {r["id"]: r["verdict"] for r in j.get("rules", [])}
        check(vd.get("bytes") == "pass", f"uart bytes pass, got {vd}")
        check(vd.get("noerr") == "fail", "uart no_errors fails (fixture has a bad frame)")
        check(p.returncode == 5, "exit 5")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if failures:
        print(f"{len(failures)} golden analysis failure(s):")
        for f in failures:
            print("  -", f)
        return 1
    print("golden analysis tests: all passed (synthetic fixtures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
